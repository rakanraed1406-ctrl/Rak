function AddPropToPlayer(propName, bone, off1, off2, off3, rot1, rot2, rot3)
    local ped = PlayerPedId()
    local propData = attachPropList[propName]
    local modelHash = 0

    if propData then
        modelHash = GetHashKey(propData.model)
        bone = propData.bone or bone or 28422
        off1 = propData.x or off1 or 0.0
        off2 = propData.y or off2 or 0.0
        off3 = propData.z or off3 or 0.0
        rot1 = propData.xR or rot1 or 0.0
        rot2 = propData.yR or rot2 or 0.0
        rot3 = propData.zR or rot3 or 0.0
    else
        modelHash = GetHashKey(propName)
    end

    if not IsModelInCdimage(modelHash) then return false end
    RequestModel(modelHash)
    while not HasModelLoaded(modelHash) do Wait(10) end

    local coords = GetEntityCoords(ped)
    local propObj = CreateObject(modelHash, coords.x, coords.y, coords.z, true, true, true)
    AttachEntityToEntity(propObj, ped, GetPedBoneIndex(ped, bone), off1, off2, off3, rot1, rot2, rot3, true, true, false, true, 1, true)
    table.insert(PlayerProps, propObj)
    SetModelAsNoLongerNeeded(modelHash)
    return propObj
end

function DestroyAllProps()
    for _, prop in ipairs(PlayerProps or {}) do
        if DoesEntityExist(prop) then
            DeleteEntity(prop)
        end
    end
    PlayerProps = {}

    for _, prop in ipairs(PlayerProps2 or {}) do
        if DoesEntityExist(prop) then
            DeleteEntity(prop)
        end
    end
    PlayerProps2 = {}
end

RegisterNetEvent("Dh-animmenu:propattach:attachItem", function(propName, ped)
    AddPropToPlayer(propName)
end)

RegisterNetEvent("Dh-animmenu:propattach:destroyProp", function(ped)
    DestroyAllProps()
end)

RegisterNetEvent("cylex_animmenuv2:propattach:attachItem", function(propName, ped)
    AddPropToPlayer(propName)
end)

RegisterNetEvent("cylex_animmenuv2:propattach:destroyProp", function(ped)
    DestroyAllProps()
end)
